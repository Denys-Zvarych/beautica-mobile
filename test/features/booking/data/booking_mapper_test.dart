// Phase 14.0 — Regression: BookingMapper.fromDto / fromDtoList resilience to
// an unrecognised BookingDetailResponse.status wire value.
//
// WHY THIS FILE EXISTS
// ---------------------
// Flagged by mobile-security during the Phase 14.0 re-audit: `BookingMapper
// .fromDto` catches the `ArgumentError` thrown by [BookingStatus.fromWire]
// for a status value it doesn't recognise and rethrows it as [UnknownFailure]
// (see the file header of `booking_mapper.dart`), and `fromDtoList`'s
// `on Failure { continue; }` loop is documented to drop just that one row
// and keep the rest of the page. Neither half of that contract had a test.
//
// CONSTRUCTION NOTE: `BookingDetailResponseStatusEnum` (generated by
// openapi-generator/built_value) exposes only a PRIVATE named constructor —
// the only instances reachable through its public API are the 6 known wire
// values (PENDING/CONFIRMED/COMPLETED/DECLINED/CANCELLED/NOT_COMPLETED),
// which is exactly the set [BookingStatus.fromWire] already maps 1:1. There
// is therefore no way to round-trip an "unrecognised" status through the
// typed builder OR through `standardSerializers.deserialize` (the generated
// enum serializer itself throws before a `BookingDetailResponse` could ever
// exist with a bad status — see `booking_repository_test.dart`'s
// `getMyBookings`/`getBookingById` groups, which cover the actually-reachable
// deserialization-failure paths at the wire boundary).
//
// To exercise `BookingMapper.fromDto`'s catch block specifically, this file
// fabricates a status value via `implements BookingDetailResponseStatusEnum`
// (the generated class carries no `final`/`sealed`/`base` modifier, so an
// unrelated class may structurally implement it) rather than extending it —
// this reaches exactly the code path `fromDto` executes
// (`BookingStatus.fromWire(statusDto.name)`) without going through any wire
// deserialization at all.
//
// Pure Dart unit test: no widget tree, no network, no Dio mocks.

import 'package:beautica_api/beautica_api.dart';
import 'package:beautica_mobile/core/errors/failures.dart';
import 'package:beautica_mobile/features/booking/data/booking_mapper.dart';
import 'package:beautica_mobile/features/booking/domain/booking_status.dart';
import 'package:flutter_test/flutter_test.dart';

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/// A [BookingDetailResponseStatusEnum]-compatible fake carrying a wire name
/// no real backend status maps to. Assignable to
/// `BookingDetailResponseBuilder.status` because Dart structural typing does
/// not require extending the class, only implementing its member surface.
class _UnrecognisedStatus implements BookingDetailResponseStatusEnum {
  @override
  String get name => 'RESCHEDULED'; // hypothetical future backend status

  @override
  String toString() => name;
}

BookingDetailResponse _validDto({
  required String id,
  BookingDetailResponseStatusEnum status =
      BookingDetailResponseStatusEnum.PENDING,
}) =>
    (BookingDetailResponseBuilder()
          ..id = id
          ..masterId = 'master-1'
          ..masterServiceId = 'service-1'
          ..masterFirstName = 'Оля'
          ..masterLastName = 'Коваль'
          ..serviceName = 'Манікюр'
          ..status = status
          ..startsAt = DateTime.utc(2026, 7, 10, 10)
          ..endsAt = DateTime.utc(2026, 7, 10, 11)
          ..priceAtBooking = 500
          ..durationMinutesAtBooking = 60
          ..canReview = false
          ..masterType = BookingDetailResponseMasterTypeEnum.INDEPENDENT_MASTER)
        .build();

BookingDetailResponse _dtoWithUnrecognisedStatus(String id) =>
    (BookingDetailResponseBuilder()
          ..id = id
          ..masterId = 'master-1'
          ..masterServiceId = 'service-1'
          ..masterFirstName = 'Оля'
          ..masterLastName = 'Коваль'
          ..serviceName = 'Манікюр'
          ..status = _UnrecognisedStatus()
          ..startsAt = DateTime.utc(2026, 7, 10, 10)
          ..endsAt = DateTime.utc(2026, 7, 10, 11)
          ..priceAtBooking = 500
          ..durationMinutesAtBooking = 60
          ..canReview = false
          ..masterType = BookingDetailResponseMasterTypeEnum.INDEPENDENT_MASTER)
        .build();

void main() {
  group('BookingStatus.fromWire', () {
    test('throws ArgumentError on an unrecognised wire value', () {
      expect(() => BookingStatus.fromWire('RESCHEDULED'), throwsArgumentError);
    });
  });

  group('BookingMapper.fromDto — unrecognised status', () {
    test('throws UnknownFailure instead of the raw ArgumentError', () {
      final dto = _dtoWithUnrecognisedStatus('booking-bad');

      expect(() => BookingMapper.fromDto(dto), throwsA(isA<UnknownFailure>()));
    });
  });

  group('BookingMapper.fromDtoList — resilience loop', () {
    test('drops the row with an unrecognised status and keeps the valid rows, '
        'preserving order', () {
      final dtos = <BookingDetailResponse>[
        _validDto(id: 'booking-1'),
        _dtoWithUnrecognisedStatus('booking-bad'),
        _validDto(
          id: 'booking-2',
          status: BookingDetailResponseStatusEnum.COMPLETED,
        ),
      ];

      final result = BookingMapper.fromDtoList(dtos);

      expect(result, hasLength(2));
      expect(result[0].id, 'booking-1');
      expect(result[0].status, BookingStatus.pending);
      expect(result[1].id, 'booking-2');
      expect(result[1].status, BookingStatus.completed);
    });

    test('an all-bad list maps to an empty list, not a thrown error', () {
      final dtos = <BookingDetailResponse>[
        _dtoWithUnrecognisedStatus('booking-bad-1'),
        _dtoWithUnrecognisedStatus('booking-bad-2'),
      ];

      final result = BookingMapper.fromDtoList(dtos);

      expect(result, isEmpty);
    });

    test('also drops a row with a missing required field (ServerFailure), '
        'confirming the loop catches every Failure subtype, not just '
        'UnknownFailure', () {
      final dtos = <BookingDetailResponse>[
        _validDto(id: 'booking-1'),
        BookingDetailResponseBuilder().build(), // id left unset
      ];

      final result = BookingMapper.fromDtoList(dtos);

      expect(result, hasLength(1));
      expect(result.single.id, 'booking-1');
    });
  });
}
